// Helper to generate a realistic sleeper & seater bus layout
export function generateBusSeats(busType: string, basePrice: number): Seat[] {
  const seats: Seat[] = [];
  
  if (busType.includes('SLEEPER')) {
    // Upper Deck (15 Sleeper Berths: 5 rows x 3 berths: 1 single, 2 double)
    for (let r = 1; r <= 5; r++) {
      // Single Berth (Window Left)
      seats.push({
        id: `U${r}A`,
        seatNumber: `U${r}A`,
        deck: 'UPPER',
        row: r,
        column: 1,
        type: 'SLEEPER',
        basePrice: basePrice + 120,
        status: r === 2 ? 'BOOKED' : r === 4 ? 'FEMALE_RESERVED' : 'AVAILABLE',
        isWindow: true,
      });
      // Double Berth (Right 1)
      seats.push({
        id: `U${r}B`,
        seatNumber: `U${r}B`,
        deck: 'UPPER',
        row: r,
        column: 3,
        type: 'SLEEPER',
        basePrice: basePrice + 100,
        status: r === 1 ? 'BOOKED' : 'AVAILABLE',
        isWindow: false,
      });
      // Double Berth (Right 2 Window)
      seats.push({
        id: `U${r}C`,
        seatNumber: `U${r}C`,
        deck: 'UPPER',
        row: r,
        column: 4,
        type: 'SLEEPER',
        basePrice: basePrice + 100,
        status: r === 1 ? 'BOOKED' : r === 3 ? 'FEMALE_RESERVED' : 'AVAILABLE',
        isWindow: true,
      });
    }

    // Lower Deck (15 Sleeper Berths or 15 Seaters)
    for (let r = 1; r <= 5; r++) {
      seats.push({
        id: `L${r}A`,
        seatNumber: `L${r}A`,
        deck: 'LOWER',
        row: r,
        column: 1,
        type: 'SLEEPER',
        basePrice: basePrice,
        status: r === 1 || r === 3 ? 'BOOKED' : 'AVAILABLE',
        isWindow: true,
      });
      seats.push({
        id: `L${r}B`,
        seatNumber: `L${r}B`,
        deck: 'LOWER',
        row: r,
        column: 3,
        type: 'SLEEPER',
        basePrice: basePrice,
        status: r === 4 ? 'FEMALE_RESERVED' : 'AVAILABLE',
        isWindow: false,
      });
      seats.push({
        id: `L${r}C`,
        seatNumber: `L${r}C`,
        deck: 'LOWER',
        row: r,
        column: 4,
        type: 'SLEEPER',
        basePrice: basePrice,
        status: r === 2 ? 'BOOKED' : 'AVAILABLE',
        isWindow: true,
      });
    }
  } else {
    // 2+2 Luxury Seater Bus Layout (40 seats on single lower deck)
    for (let r = 1; r <= 10; r++) {
      seats.push({
        id: `S${r}A`,
        seatNumber: `${r}A`,
        deck: 'LOWER',
        row: r,
        column: 1,
        type: 'SEATER',
        basePrice: basePrice,
        status: r === 1 || r === 5 ? 'BOOKED' : 'AVAILABLE',
        isWindow: true,
      });
      seats.push({
        id: `S${r}B`,
        seatNumber: `${r}B`,
        deck: 'LOWER',
        row: r,
        column: 2,
        type: 'SEATER',
        basePrice: basePrice - 30,
        status: r === 3 ? 'FEMALE_RESERVED' : 'AVAILABLE',
        isWindow: false,
      });
      seats.push({
        id: `S${r}C`,
        seatNumber: `${r}C`,
        deck: 'LOWER',
        row: r,
        column: 4,
        type: 'SEATER',
        basePrice: basePrice - 30,
        status: r === 2 ? 'BOOKED' : 'AVAILABLE',
        isWindow: false,
      });
      seats.push({
        id: `S${r}D`,
        seatNumber: `${r}D`,
        deck: 'LOWER',
        row: r,
        column: 5,
        type: 'SEATER',
        basePrice: basePrice,
        status: r === 7 ? 'BOOKED' : 'AVAILABLE',
        isWindow: true,
      });
    }
  }

  return seats;
}

